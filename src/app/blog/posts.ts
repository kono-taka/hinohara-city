export function formatDate(iso: string): string {
  const [y, m, d] = iso.split("-").map(Number);
  return `${y}年${m}月${d}日`;
}

export function formatReiwa(iso: string): string {
  const [y, m, d] = iso.split("-").map(Number);
  return `令和${y - 2018}年${m}月${d}日`;
}
